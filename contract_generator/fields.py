#: Обратная совместимость: канонический ключ -> основная метка Excel.
FIELD_MAPPING: Dict[str, str] = {
    spec.key: spec.aliases[0] for spec in FIELD_SPECS if spec.aliases
}

_SPACES_RE = re.compile(r"\s+")


def normalize_label(label: object) -> str:
    """Приводит метку поля к канонической форме для сравнения.

    Убирает пробелы по краям и повторяющиеся, снимает завершающие двоеточия,
    приводит к нижнему регистру и заменяет ``ё`` на ``е``.
    """
    if label is None:
        return ""
    text = str(label).replace(" ", " ")
    text = _SPACES_RE.sub(" ", text).strip()
    text = text.rstrip(":;").strip()
    return text.lower().replace("ё", "е")


def _build_alias_index() -> Dict[str, str]:
    index: Dict[str, str] = {}
    for spec in FIELD_SPECS:
        for alias in spec.aliases:
            norm = normalize_label(alias)
            if norm and norm not in index:
                index[norm] = spec.key
    return index


#: Нормализованная метка Excel -> канонический ключ поля.
ALIAS_INDEX: Dict[str, str] = _build_alias_index()


def resolve_field(label: object) -> Optional[str]:
    """Возвращает канонический ключ поля по метке из Excel, либо ``None``."""
    return ALIAS_INDEX.get(normalize_label(label))


def display_name(key: str) -> str:
    """Русское отображаемое имя поля."""
    spec = FIELDS_BY_KEY.get(key)
    return spec.display if spec else key


def fields_in_group(group: str, editable_only: bool = False) -> List[FieldSpec]:
    """Поля группы; при ``editable_only`` — только показываемые в таблице."""
    return [
        spec for spec in FIELD_SPECS
        if spec.group == group and (spec.show_in_editor or not editable_only)
    ]


#: Поля, редактируемые в общей таблице интерфейса.
EDITOR_FIELDS: Tuple[FieldSpec, ...] = tuple(
    spec for spec in FIELD_SPECS if spec.show_in_editor
)
